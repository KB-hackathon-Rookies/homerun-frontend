/**
 * 코치 시트의 내용 형태.
 *
 * 시안은 여정 화면마다 오른쪽 아래에 `FAB/코치` 를 두고, 누르면 딤 위로
 * `Sheet/코치 TIME` 이 올라온다. 화면 위에 한 줄로 붙는 코치 팁과는 다른
 * 자리다 — 팁은 지금 이 화면에서 뭘 하라는 말이고, 시트는 **왜 그래야 하는지**를
 * 푼다.
 *
 * 1루와 2루가 각자 같은 모양을 따로 들고 있었다. 한 화면에 시트가 둘이 되면
 * 어느 쪽 문구를 고쳐야 하는지 알 수 없어서, 형태를 여기 하나로 모았다.
 * 내용(무슨 말을 하는지)은 화면 쪽에 그대로 둔다.
 */

/** 사전 문답 한 쌍. 시안의 `qa` 블록이다. */
export interface CoachQa {
  q: string;
  a: string;
}

export interface CoachSheet {
  /** 시트 머리의 제목. "코치 TIME" 아래에 붙는다. */
  title: string;
  /** 코치가 먼저 건네는 말. 반말인 것은 코치가 옆에서 거드는 자리라서다. */
  intro: string;
  qa: CoachQa[];
  /** 더 알아보기 칩 → `/coach/{id}`. 모듈이 실제로 있는 것만 건다. */
  related?: { id: string; label: string }[];
}
